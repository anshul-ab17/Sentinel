import { writeFile, mkdir } from "node:fs/promises";

import { buildApi } from "../apps/server/src/api.ts";
const app = await buildApi();
try {
  await app.ready();
  const specification = app.swagger();
  await mkdir(new URL("../packages/api-client/", import.meta.url), { recursive: true });
  await writeFile(
    new URL("../packages/api-client/openapi.json", import.meta.url),
    JSON.stringify(specification, null, 2) + "\n",
  );
  const routes = Object.entries(specification.paths).flatMap(([path, item]) =>
    Object.keys(item)
      .filter((m) => ["get", "post", "patch", "put", "delete"].includes(m))
      .map((method) => `${method.toUpperCase()} ${path}`),
  );
  await writeFile(
    new URL("../packages/api-client/routes.ts", import.meta.url),
    "// Generated by scripts/generate-api.mjs; do not edit.\nexport const routes = " +
      JSON.stringify(routes, null, 2) +
      " as const;\n",
  );
} finally {
  await app.close();
}
